// Run with a built Node SDK checkout; only captures emitBus, never opens a socket.
import { writeFileSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

if (!process.argv[2]) throw new Error("usage: node tools/generate-introspection-vector.mjs NODE_SDK");
const sdk = resolve(process.argv[2]);
const { HiveMindHttpTransport } = await import(pathToFileURL(resolve(sdk, "dist/src/transport-core.js")));
const peer = Object.create(HiveMindHttpTransport.prototype);
let frame;
peer.sendHiveMessage = async (message) => { frame = JSON.stringify(message); };
await peer.emitBus("ovos.skills.fallback.list", {}, {
  request_id: "req-1", thalovant_request_id: "req-1", lang: "en-us",
  session: { session_id: "sess-1", site_id: "kitchen", lang: "en-us", request_id: "req-1" },
});
const { version } = JSON.parse(readFileSync(resolve(sdk, "package.json"), "utf8"));
writeFileSync(new URL("../tests/fixtures/introspection-node.h", import.meta.url),
  `/* Generated by the Node SDK ${version} emitBus implementation. */\n` +
  `static const char FALLBACK_REQUEST_NODE[] = ${JSON.stringify(frame)};\n`);
